import numpy as np


def N(A, v): # neighbors of v
  v_num, _ = A.shape
  vertices = range(v_num)
  return [u for u in vertices if A[u][v] == 1]

def pairR2(A, v, degree):
  # valid neighbors: two nonadjacent neighbors of v with degree at most 7
  r = [u for u in N(A, v) if degree[u] <= 7]
  for i in range(len(r)):
    for j in range(i+1, len(r)):
      if A[r[i]][r[j]] == 0:
        return (r[i],r[j])
  return False # doesnt have valid neighbors

def checkR2(A, v, degree): # condition for being in R(2)
  if degree[v] != 5: return False # vertex of degree = 5
  if pairR2(A, v, degree): # has valid neighbors
    return True
  return False

def updateReadyLists(A, w, degree, R1, R2):
  if checkR2(A, w, degree): # check if w is supposed to be in R2
    R2.append(w)
  elif degree[w] == 4: # check if w is supposed to be in R1
    try: R2.remove(w)
    except: pass
    R1.append(w)
  elif degree[w] == 7:
    # check if any neighbor of w is supposed to be in R2
    for u in N(A, w):
      if checkR2(A, u, degree) and u not in R2: R2.append(u)

def deleteVertex(A, v, degree, R1, R2):
  for w in N(A, v): # for every neighbor of v
    A[v][w] = 0 # w no longer adjacent with v
    A[w][v] = 0
    degree[w] += -1 # decrement degree of w
    updateReadyLists(A, w, degree, R1, R2)
  return A

def identifyVertices(A, u, v, degree, R1, R2, stack):
  #print(f"Identifying {u} and {v}")
  Nv = [] # for vertices marked with v
  for w in N(A, v):
    Nv.append(w)
  for w in N(A, u):
    A[u][w] = 0 # delete w from adjacency with u
    A[w][u] = 0
    if w not in Nv:
      A[v][w] = 1 # v and w are now adjacent
      A[w][v] = 1
      degree[v] += 1
      if degree[v] == 6 and v in R2:
        R2.remove(v)
    else:
      degree[w] += -1
      updateReadyLists(A, w, degree, R1, R2)
  if u in R2:
    R2.remove(u)
    stack.append((u, v))
  return A

def Frederickson1984(A):
# INPUT: Adjacency Matrix A dari suatu graf G
# OUTPUT: Pemetaan dari vertex set G ke {0, 1, 2, 3, 4}

  v_num, _ = A.shape
  vertices = range(v_num)
  stack = []
  degree = {v:sum(A[:,v]) for v in vertices} # degrees of each vertex
  R1 = [v for v in vertices if degree[v] < 5] # every vertex of degree < 5
  R2 = [v for v in vertices if checkR2(A, v, degree)]

  # Tahap 1: Reduksi
  Ared = A.copy() # copy of adjacency matrix for deletion
  while R1 or R2: # if R(1) or R(2) is not empty
    if R1: # R(1) non empty
      v = R1.pop()
      stack.append((v, N(Ared, v).copy()))
      deleteVertex(Ared, v, degree, R1, R2)
    else: # R(2) non empty
      v = R2.pop()
      (x, y) = pairR2(Ared, v, degree) # nonadjacent neighbors of v with degree at most 7
      identifyVertices(Ared, x, y, degree, R1, R2, stack)
      stack.append((v, N(Ared, v).copy()))
      deleteVertex(Ared, v, degree, R1, R2)
  # Tahap 2: Coloring
  colors = range(0, 5)
  coloring = {v:None for v in vertices}

  while stack:
    v, t = stack.pop()
    if isinstance(t, list): # if t is an adjacency list
      Nv = N(A, v)
      usedColors = {coloring[u] for u in t if coloring[u] is not None}
      validColors = [color for color in colors if color not in usedColors]
      coloring[v] = validColors[0]
    else: # v, t is vertex pair
      coloring[v] = coloring[t]
  return coloring

